export function t(key: keyof typeof translations['pt'], locale: Locale = 'pt', params?: Record<string, string>): string {
  let text = translations[locale]?.[key] || translations['pt'][key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, v);
    });
  }
  return text;
}
